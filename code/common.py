"""Core data, schema, harmonizer, models and pipeline for the PTB-XL multimodal robustness study.

Design notes
- Cohort: records whose diagnostic superclass set is exactly {MI} (y=1) or exactly {NORM} (y=0),
  using every diagnostic SCP statement present in scp_codes (standard aggregation, any likelihood).
- Folds: dataset-provided strat_fold. 1-8 train, 9 validation, 10 test (patients never span folds; verified in tests).
- Modalities: three ECG feature views (12SL, ECGDeli, Uni-G, PTB-XL+), structured data (age, sex, height, weight),
  and the free-text report (used only by a separate, label-leaking audit model; never by the signal pipeline).
"""
import ast
import re
import time
import resource
from dataclasses import dataclass, field
import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression

LEADS = ["I", "II", "III", "aVR", "aVL", "aVF", "V1", "V2", "V3", "V4", "V5", "V6"]
VIEWS = ["12sl", "ecgdeli", "unig"]
STRUCT = ["age", "sex", "height", "weight"]
SEED = 20261025
LEAD_RE = re.compile(r"^(.*)_(%s)$" % "|".join(map(re.escape, LEADS)))

# unit -> factor to canonical (mV, ms, cm, kg)
AMP_TO_CANON = {"mV": 1.0, "uV": 1e-3}
TIME_TO_CANON = {"ms": 1.0, "s": 1e3}
HEIGHT_TO_CANON = {"cm": 1.0, "in": 2.54}
WEIGHT_TO_CANON = {"kg": 1.0, "lb": 0.45359237}


def cpu_snapshot():
    return time.process_time(), resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024.0


# ----------------------------------------------------------------------------- data
def load_raw(D):
    db = pd.read_csv(f"{D}/ptbxl_database.csv", index_col="ecg_id")
    st = pd.read_csv(f"{D}/scp_statements.csv", index_col=0)
    fd = pd.read_csv(f"{D}/feature_description.csv").dropna(subset=["id"])
    views = {n: pd.read_csv(f"{D}/{n}_features.csv", low_memory=False).set_index("ecg_id") for n in VIEWS}
    return db, st, fd, views


def territory_of(codes, diag):
    """Infarct territory from the MI statements of one record: 'IMI', 'AMI', 'LMI', 'PMI' set."""
    return {diag.loc[k, "diagnostic_subclass"] for k in codes
            if k in diag.index and diag.loc[k, "diagnostic_class"] == "MI"}


def build_cohort(db, st, min_likelihood=0.0):
    diag = st[st.diagnostic == 1]
    scp = db.scp_codes.apply(ast.literal_eval)
    sup = scp.apply(lambda d: frozenset(diag.loc[k, "diagnostic_class"] for k, v in d.items()
                                        if k in diag.index and v >= min_likelihood))
    keep = (sup == frozenset({"MI"})) | (sup == frozenset({"NORM"}))
    c = db.loc[keep, ["patient_id", "age", "sex", "height", "weight", "report", "strat_fold",
                      "validated_by_human", "initial_autogenerated_report", "site", "device"]].copy()
    c["y"] = (sup[keep] == frozenset({"MI"})).astype(int)
    terr = scp[keep].apply(lambda d: territory_of(d, diag))
    c["terr"] = terr.apply(lambda s: "+".join(sorted(s)) if s else "")
    c["fold"] = c.strat_fold.astype(int)
    return c


def schema_for(columns, fd):
    """Per feature column: view, base id, lead, unit, kind (value/iqr/count)."""
    units = dict(zip(fd["id"], fd["unit"]))
    rows = []
    for col in columns:
        if col.startswith("struct::"):
            nm = col.split("::")[1]
            rows.append(dict(col=col, view="struct", base=nm, lead=None, kind="value",
                             unit={"age": "years", "sex": "code", "height": "cm", "weight": "kg"}[nm]))
            continue
        view, name = col.split("::", 1)
        kind = "value"
        m = re.search(r"_(iqr|count)$", name)
        base = name
        if m:
            kind = m.group(1)
            base = name[:m.start()]
        ml = LEAD_RE.match(base)
        lead = ml.group(2) if ml else None
        fid = ml.group(1) + "_X" if ml else base
        unit = units.get(fid)
        if unit is None and base.startswith("P_Term"):
            unit = "ms"          # undocumented in feature_description.csv; a duration like its siblings
        if kind == "count":
            unit = "integer"
        rows.append(dict(col=col, view=view, base=base, lead=lead, kind=kind, unit=unit))
    return pd.DataFrame(rows).set_index("col")


@dataclass
class Dataset:
    X: pd.DataFrame          # canonical-unit features, columns "view::name" and "struct::name"
    meta: pd.DataFrame       # cohort columns incl. y, fold, patient_id, report
    schema: pd.DataFrame


def build_dataset(D, min_likelihood=0.0):
    db, st, fd, views = load_raw(D)
    c = build_cohort(db, st, min_likelihood)
    common = c.index
    for v in views.values():
        common = common.intersection(v.index)
    c = c.loc[common]
    parts = []
    for n in VIEWS:
        v = views[n].loc[common]
        v = v.drop(columns=[x for x in v.columns if x == "ecg_id"], errors="ignore")
        v.columns = [f"{n}::{x}" for x in v.columns]
        parts.append(v.astype(float))
    s = c[STRUCT].astype(float)
    s.columns = [f"struct::{x}" for x in STRUCT]
    X = pd.concat(parts + [s], axis=1)
    return Dataset(X=X, meta=c, schema=schema_for(X.columns, fd))


# ----------------------------------------------------------------------------- raw batch + harmonizer
@dataclass
class Raw:
    """Values as supplied by a source system: numbers plus the unit tags they were recorded in."""
    X: np.ndarray
    cols: list
    tags: dict = field(default_factory=lambda: dict(amp="mV", time="ms", height="cm", weight="kg"))

    def copy(self):
        return Raw(self.X.copy(), self.cols, dict(self.tags))


def group_factors(schema):
    """Column groups whose canonical value = raw * factor(tag). Returns arrays of column indexes."""
    u = schema["unit"].fillna("")
    idx = {}
    idx["amp"] = np.where(u == "mV")[0]
    idx["time"] = np.where(u == "ms")[0]
    idx["area"] = np.where(u == "mV*ms")[0]      # amp * time
    idx["slope"] = np.where(u == "mV/ms")[0]     # amp / time
    idx["height"] = np.where(schema.index == "struct::height")[0]
    idx["weight"] = np.where(schema.index == "struct::weight")[0]
    return idx


class Harmonizer:
    """Converts a Raw batch to canonical units. `ignore` lists tag groups a (faulty) implementation fails to honour."""

    def __init__(self, schema, ignore=()):
        self.g = group_factors(schema)
        self.ignore = set(ignore)

    def factors(self, tags):
        fa = 1.0 if "amp" in self.ignore else AMP_TO_CANON[tags["amp"]]
        ft = 1.0 if "time" in self.ignore else TIME_TO_CANON[tags["time"]]
        fh = 1.0 if "height" in self.ignore else HEIGHT_TO_CANON[tags["height"]]
        fw = 1.0 if "weight" in self.ignore else WEIGHT_TO_CANON[tags["weight"]]
        return dict(amp=fa, time=ft, area=fa * ft, slope=fa / ft, height=fh, weight=fw)

    def __call__(self, raw):
        X = raw.X.copy()
        f = self.factors(raw.tags)
        for k, ix in self.g.items():
            if len(ix) and f[k] != 1.0:
                X[:, ix] = X[:, ix] * f[k]
        return X


def to_raw(ds, idx, tags=None):
    return Raw(ds.X.loc[idx].to_numpy(copy=True), list(ds.X.columns), dict(tags) if tags else dict(amp="mV", time="ms", height="cm", weight="kg"))


# ----------------------------------------------------------------------------- models
class Prep:
    """median impute -> winsorize (train percentiles) -> standardize. Used by logistic regression only."""

    def fit(self, X):
        self.med = np.nanmedian(X, axis=0)
        self.med = np.where(np.isnan(self.med), 0.0, self.med)
        Xi = np.where(np.isnan(X), self.med, X)
        self.lo, self.hi = np.percentile(Xi, 0.5, axis=0), np.percentile(Xi, 99.5, axis=0)
        Xc = np.clip(Xi, self.lo, self.hi)
        self.mu = Xc.mean(0)
        self.sd = Xc.std(0)
        self.sd[self.sd == 0] = 1.0
        return self

    def transform(self, X):
        Xi = np.where(np.isnan(X), self.med, X)
        return (np.clip(Xi, self.lo, self.hi) - self.mu) / self.sd


def make_estimator(kind):
    if kind == "hgb":
        return HistGradientBoostingClassifier(max_iter=250, learning_rate=0.06, max_leaf_nodes=15, min_samples_leaf=20,
                                              l2_regularization=1.0, early_stopping=False, random_state=SEED)
    return LogisticRegression(C=0.02, max_iter=3000, solver="lbfgs", random_state=SEED)


class FittedModel:
    def __init__(self, kind, cols_idx):
        self.kind, self.cols_idx = kind, np.asarray(cols_idx)

    def fit(self, X, y):
        # drop features observed in <2 training rows (HistGradientBoosting cannot bin them; carry no information)
        ok = np.isfinite(X[:, self.cols_idx]).sum(0) >= 2
        self.cols_idx = self.cols_idx[ok]
        Z = X[:, self.cols_idx]
        self.prep = Prep().fit(Z) if self.kind == "lr" else None
        self.est = make_estimator(self.kind).fit(self.prep.transform(Z) if self.prep else Z, y)
        return self

    def logit(self, X):
        Z = X[:, self.cols_idx]
        Z = self.prep.transform(Z) if self.prep else Z
        return self.est.decision_function(Z)


def view_cols(schema, views, struct=True):
    ix = [i for i, (c, r) in enumerate(schema.iterrows()) if r.view in views or (struct and r.view == "struct")]
    return np.array(ix)


TARGETS = {
    # name: (kind, architecture, views)
    "E-LR": ("lr", "early", VIEWS),
    "E-HGB": ("hgb", "early", VIEWS),
    "L-LR": ("lr", "late", VIEWS),
    "L-HGB": ("hgb", "late", VIEWS),
    "S-HGB": ("hgb", "single", ["12sl"]),
}


class Target:
    """Trained model(s) for one architecture. Late fusion = per-view models averaged on the logit scale
    over the views that are available (a view is unavailable when all its features are missing)."""

    def __init__(self, name, schema):
        self.name, self.schema = name, schema
        self.kind, self.arch, self.views = TARGETS[name]
        self.view_ix = {v: view_cols(schema, [v]) for v in VIEWS}
        self.view_feat_ix = {v: np.where((schema.view == v).to_numpy())[0] for v in VIEWS}

    def fit(self, X, y):
        if self.arch == "late":
            self.models = {v: FittedModel(self.kind, self.view_ix[v]).fit(X, y) for v in self.views}
        else:
            self.models = {"all": FittedModel(self.kind, view_cols(self.schema, self.views)).fit(X, y)}
        return self

    def view_available(self, X, v):
        return ~np.isnan(X[:, self.view_feat_ix[v]]).all(axis=1)

    def logit(self, X, return_parts=False):
        if self.arch != "late":
            out = self.models["all"].logit(X)
            return (out, None) if return_parts else out
        parts, avail = [], []
        for v, m in self.models.items():
            parts.append(m.logit(X))
            avail.append(self.view_available(X, v))
        P, A = np.array(parts), np.array(avail)
        cnt = A.sum(0)
        out = np.where(cnt > 0, (P * A).sum(0) / np.maximum(cnt, 1), np.nan)
        if return_parts:
            return out, (P, A)
        return out

    def proba(self, X):
        z = self.logit(X)
        return 1.0 / (1.0 + np.exp(-z))


# ----------------------------------------------------------------------------- pipeline with injectable faults
FAULTS = {
    "F1_AMP_UNIT_IGNORED": dict(ignore=("amp",)),
    "F2_TIME_UNIT_IGNORED": dict(ignore=("time",)),
    "F3_ANTHRO_UNIT_IGNORED": dict(ignore=("height", "weight")),
    "F4_SWAP_V1_V2": dict(perm=("V1", "V2")),
    "F5_LIMB_LEADS_CYCLED": dict(cycle=("I", "II", "III")),
    "F6_MISSING_ZERO_FILLED": dict(zerofill=True),
    "F7_AMP_GAIN_80PCT": dict(gain=0.8),
    "F8_SEX_CODE_FLIPPED": dict(sexflip=True),
    "F9_ECGDELI_JOIN_LOST": dict(dropview="ecgdeli"),
}


class Pipeline:
    def __init__(self, target, fault=None):
        self.t, self.fault = target, fault
        sc = target.schema
        spec = FAULTS.get(fault, {}) if fault else {}
        self.spec = spec
        self.h = Harmonizer(sc, ignore=spec.get("ignore", ()))
        self.cols = list(sc.index)
        self.col_pos = {c: i for i, c in enumerate(self.cols)}
        self.perm = self._perm(sc, spec)
        self.gain_ix = np.where(sc.unit.isin(["mV", "mV*ms"]).to_numpy() & (sc.view != "struct").to_numpy())[0]
        self.drop_ix = np.where((sc.view == spec["dropview"]).to_numpy())[0] if "dropview" in spec else None

    def _perm(self, sc, spec):
        p = np.arange(len(sc))
        def lead_map(mapping):
            """Relabel leads within every feature family (same view/stem/suffix) that exists in *all* leads of the
            mapping, so the result is a true permutation of columns."""
            fam = {}
            for i, c in enumerate(sc.index):
                lead = sc.lead.iloc[i]
                if lead in mapping:
                    m = re.search(r"_(iqr|count)$", c)
                    stem, suf = (c[: m.start()], c[m.start():]) if m else (c, "")
                    fam.setdefault((stem[: -len(lead)], suf), {})[lead] = i
            q = p.copy()
            for members in fam.values():
                if all(l in members for l in mapping):
                    for l, i in members.items():
                        q[i] = members[mapping[l]]
            return q
        if "perm" in spec:
            a, b = spec["perm"]
            return lead_map({a: b, b: a})
        if "cycle" in spec:
            a, b, c = spec["cycle"]
            return lead_map({a: b, b: c, c: a})
        return p

    def canonical(self, raw):
        X = self.h(raw)
        sp = self.spec
        if "perm" in sp or "cycle" in sp:
            X = X[:, self.perm]
        if "gain" in sp:
            X[:, self.gain_ix] *= sp["gain"]
        if sp.get("sexflip"):
            j = self.col_pos["struct::sex"]
            X[:, j] = 1.0 - X[:, j]
        if "dropview" in sp:
            X[:, self.drop_ix] = np.nan
        if sp.get("zerofill"):
            X = np.where(np.isnan(X), 0.0, X)
        return X

    def logit(self, raw, parts=False):
        return self.t.logit(self.canonical(raw), return_parts=parts)

    def proba(self, raw):
        z = self.logit(raw)
        return 1.0 / (1.0 + np.exp(-z))
